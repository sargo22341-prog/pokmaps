            GameVersion.CRYSTAL, GameVersion.RUBY, GameVersion.SAPPHIRE, GameVersion.EMERALD,
            GameVersion.FIRERED, GameVersion.LEAFGREEN -> error("Version Sinnoh attendue : $version")
